    (SELECT versionId FROM version
     WHERE mixId = (SELECT mixId FROM mix WHERE internalTitle = 'Phoenix 2')
     AND internalTitle = 'v1.01.0'),
    d.ancestorId,
    (SELECT sortOrder FROM version
     WHERE mixId = (SELECT mixId FROM mix WHERE internalTitle = 'Phoenix 2')
     AND internalTitle = 'v1.01.0'),
    d.ancestorSortOrder
